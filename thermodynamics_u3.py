    def calcular_velocidad_salida(d1, d2, v1, vesp1, vesp2):
        """
        Calcula la velocidad de salida v2 utilizando la conservación de la masa.
        """

        A1 = math.pi * (d1 / 2) ** 2
        A2 = math.pi * (d2 / 2) ** 2


        rho1 = 1 / vesp1  # lbm/ft^3
        rho2 = 1 / vesp2  # lbm/ft^3


        v2 = (rho1 * A1 * v1) / (rho2 * A2)
        return v2

    def calcular_potencia(d1, d2, v1, v2, h1, h2, vesp1, vesp2):
        """
        Calcula la potencia de salida de la turbina.
        """
        # Conversión de diámetros a áreas (ft^2)
        A1 = math.pi * (d1 / 2) ** 2
        A2 = math.pi * (d2 / 2) ** 2

        # Densidades (1 / volumen específico)
        rho1 = 1 / vesp1  # lbm/ft^3
        rho2 = 1 / vesp2  # lbm/ft^3

        # Gasto másico (lbm/s)
        mdot = rho1 * A1 * v1

        # Velocidades cuadradas
        v1_squared = v1 ** 2
        v2_squared = v2 ** 2

        # Potencia (ft-lbf/s)
        potencia = mdot * ((h1 - h2) + (v1_squared - v2_squared) / 2)

        # Conversión a caballos de fuerza (hp)
        potencia_hp = potencia / 550  # 1 hp = 550 ft-lbf/s

        return potencia_hp

