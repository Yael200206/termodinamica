    # Función para calcular el flujo volumétrico en la salida de la tobera
    def calcular_flujo_volumetrico_salida(T1, P1, velocidad_entrada, T2, P2, perdida_calor, area_entrada):
        # Conversión de unidades
        area_entrada_m2 = area_entrada / 10000  # cm² a m²
        T1_kelvin = T1 + 273.15  # Convertir temperatura a Kelvin
        T2_kelvin = T2 + 273.15  # Convertir temperatura a Kelvin
        perdida_calor_watts = perdida_calor * 1000  # kW a W

        # Suposiciones:
        # - Proceso adiabático si ignoramos las pérdidas de calor (para simplificación)
        # - Velocidad de salida asumiendo que la conservación de energía en flujo es aplicable

        # Energía por conservación de energía (trabajo mecánico y calor)
        h1 = R * T1_kelvin  # Asumir H1 en función de T1 para simplificación
        h2 = h1 - perdida_calor_watts  # Asumir H2 = H1 - pérdida de calor

        # Velocidad de salida usando conservación de energía: V2
        velocidad_salida = math.sqrt(velocidad_entrada**2 + 2 * (h1 - h2))

        # Flujo másico: ṁ = (densidad1 * area_entrada * velocidad_entrada)
        # Simplificación con gas ideal
        densidad1 = P1 * 1000 / (R * T1_kelvin)
        flujo_masico = densidad1 * area_entrada_m2 * velocidad_entrada

        # Densidad de salida
        densidad2 = P2 * 1000 / (R * T2_kelvin)

        # Flujo volumétrico de salida: V̇ = flujo_masico / densidad2
        flujo_volumetrico_salida = flujo_masico / densidad2

        return round(flujo_volumetrico_salida, 4)

