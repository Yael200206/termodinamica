    def calcular_velocidad_salida():
        print("Cálculo de la velocidad de salida del vapor de agua en una tobera")

        # Ingreso de datos
        T_entrada = float(input("Ingrese la temperatura de entrada (°C): ")) + 273.15  # Convertimos °C a K
        P_entrada = float(input("Ingrese la presión de entrada (kPa): ")) * 1000  # Convertimos kPa a Pa
        T_salida = float(input("Ingrese la temperatura de salida (°C): ")) + 273.15  # Convertimos °C a K
        P_salida = float(input("Ingrese la presión de salida (kPa): ")) * 1000  # Convertimos kPa a Pa
        v_entrada = float(input("Ingrese la velocidad de entrada (m/s): "))
        Q_perdida = float(input("Ingrese la tasa de pérdida de calor (kW): ")) * 1000  # Convertimos kW a W
        A_entrada = float(input("Ingrese el área de entrada (cm²): ")) * 1e-4  # Convertimos cm² a m²

        # Cálculo de entalpías y densidad usando CoolProp
        h_entrada = PropsSI('H', 'P', P_entrada, 'T', T_entrada, 'Water')  # En J/kg
        h_salida = PropsSI('H', 'P', P_salida, 'T', T_salida, 'Water')  # En J/kg
        rho_entrada = PropsSI('D', 'P', P_entrada, 'T', T_entrada, 'Water')  # En kg/m³

        # Cálculo del flujo másico
        m_dot = rho_entrada * v_entrada * A_entrada

        # Aplicación de la ecuación de conservación de la energía para despejar la velocidad de salida
        v_salida = math.sqrt(2 * ((h_entrada - h_salida - (Q_perdida / m_dot)) + (v_entrada**2 / 2)))

        # Resultado
        print(f"La velocidad de salida del vapor de agua es: {v_salida:.2f} m/s")

    # Llamar a la función para ejecutar el cálculo
    calcular_velocidad_salida()

    # Energía transferida como trabajo (SI LA ENERGÍA DISMINUYE, EL RESULTADO SERA - .SI LA ENERGIA AUMENTA, EL RESULTADO SERA +)
    def calcular_trabajo(Q, delta_U):
        """
        Calcula la energía transferida como trabajo utilizando la primera ley de la termodinámica.
        """
        # Primera ley de la termodinámica: Q = ΔU + W => W = Q - ΔU
        W = Q - (delta_U)  # Cambiamos el signo de
        return W

