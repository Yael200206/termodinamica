    # Función para calcular el calor transferido en una compresión isotérmica
    def calcular_calor_transferido(P_inicial, P_final, T):
        # Conversión de temperatura de Celsius a Kelvin
        T_kelvin = T + 273.15

        # Cálculo del trabajo (y calor transferido) en proceso isotérmico
